#!/usr/bin/env python3
"""Turn the scraped JSON in ../data/ into readable Markdown in ../docs/.

    python3 scraper/build_docs.py

Standard library only. Safe to rerun: it rewrites every generated file.
"""
import html
import json
import re
import shutil
from datetime import datetime
from html.parser import HTMLParser
from pathlib import Path
from zoneinfo import ZoneInfo

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
DOCS = ROOT / "docs"
SITE = "https://www.spaceappschallenge.org"
MELBOURNE = ZoneInfo("Australia/Melbourne")
GENERATED = "<!-- Generated by scraper/build_docs.py from data/. Do not edit by hand. -->\n\n"


class Markdown(HTMLParser):
    """Small HTML to Markdown converter for the site's rich text."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.out = []
        self.links = []
        self.lists = []   # [tag, item count, indent] per open list
        self.quotes = []  # index in self.out where each open blockquote starts
        self.marks = []   # (marker, index in self.out) for open bold/italic

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag in ("p", "div"):
            if not self.at_list_marker():
                self.out.append("\n\n")
        elif tag == "br":
            self.out.append("\\\n")
        elif tag in ("b", "strong", "i", "em"):
            self.open_mark("**" if tag in ("b", "strong") else "*")
        elif re.fullmatch(r"h[1-6]", tag):
            self.out.append("\n\n" + "#" * min(6, int(tag[1]) + 1) + " ")
        elif tag in ("ul", "ol"):
            indent = ""
            if self.lists:
                parent = self.lists[-1]
                width = len(f"{parent[1]}. ") if parent[0] == "ol" else 2
                indent = parent[2] + " " * width
            self.lists.append([tag, 0, indent])
            self.out.append("\n")
        elif tag == "li":
            kind, _, indent = self.lists[-1] if self.lists else ("ul", 0, "")
            if kind == "ol":
                self.lists[-1][1] += 1
                self.out.append(f"\n{indent}{self.lists[-1][1]}. ")
            else:
                self.out.append(f"\n{indent}- ")
        elif tag == "a":
            self.links.append(a.get("href") or "")
            self.out.append("[")
        elif tag == "img":
            self.out.append(f"![{a.get('alt') or ''}]({a.get('src') or ''})")
        elif tag == "blockquote":
            self.out.append("\n\n")
            self.quotes.append(len(self.out))
        elif tag == "tr":
            self.out.append("\n| ")

    def handle_endtag(self, tag):
        if tag in ("p", "div") or re.fullmatch(r"h[1-6]", tag):
            self.out.append("\n\n")
        elif tag in ("b", "strong", "i", "em"):
            self.close_mark("**" if tag in ("b", "strong") else "*")
        elif tag in ("ul", "ol"):
            if self.lists:
                self.lists.pop()
            self.out.append("\n\n")
        elif tag == "a":
            href = self.links.pop() if self.links else ""
            if href.startswith("/"):
                href = SITE + href
            self.out.append(f"]({href})" if href else "]")
        elif tag == "blockquote" and self.quotes:
            start = self.quotes.pop()
            body = re.sub(r"\n\s*\n\s*", "\n\n", "".join(self.out[start:])).strip()
            quoted = "\n".join("> " + line if line.strip() else ">" for line in body.split("\n"))
            self.out[start:] = [quoted, "\n\n"]
        elif tag in ("td", "th"):
            self.out.append(" | ")

    def at_list_marker(self):
        """True right after a list bullet, so <li><p> doesn't leave it empty."""
        last = "".join(self.out[-2:])
        return bool(self.lists) and re.search(r"(^|\n)[ ]*(- |\d+\. )$", last) is not None

    def open_mark(self, marker):
        self.marks.append((marker, len(self.out)))
        self.out.append(marker)

    def close_mark(self, marker):
        """Close bold/italic. Tags closed out of order close the inner mark too."""
        if not any(m == marker for m, _ in self.marks):
            return
        while self.marks:
            current, start = self.marks.pop()
            inner = "".join(self.out[start + 1:])
            if not inner.strip():
                self.out[start:] = [inner]  # empty mark: drop it
            else:
                lead = inner[:len(inner) - len(inner.lstrip())]
                trail = inner[len(inner.rstrip()):]
                self.out[start:] = [lead, current, inner.strip(), current, trail]
            if current == marker:
                return

    def handle_data(self, data):
        self.out.append(re.sub(r"\s+", " ", data))

    def text(self):
        for _, start in reversed(self.marks):  # unclosed bold/italic: drop the marker
            self.out[start] = ""
        md = "".join(self.out)
        md = re.sub(r"[ \t]+\n", "\n", md)
        md = re.sub(r"(?m)^[ \t]+(?=\S)(?![-*] |\d+\. )", "", md)  # stray indent would render as code
        md = re.sub(r"\n{3,}", "\n\n", md)
        return md.strip()


def md(fragment):
    if not fragment:
        return ""
    if "<" not in fragment:  # plain text, maybe with entities like &lt;canvas&gt;
        return re.sub(r"[ \t]+", " ", html.unescape(fragment)).strip()
    parser = Markdown()
    parser.feed(fragment)
    parser.close()
    return parser.text()


def cell(value):
    """Make a value safe inside a Markdown table cell."""
    return re.sub(r"\s+", " ", str(value if value is not None else "")).replace("|", "\\|").strip()


def melbourne_date(stamp):
    """ISO timestamp to a Melbourne calendar date. Naive stamps are already local."""
    if not stamp:
        return "?"
    moment = datetime.fromisoformat(stamp.replace("Z", "+00:00"))
    if moment.tzinfo:
        moment = moment.astimezone(MELBOURNE)
    return moment.date().isoformat()


def can_join(team):
    return bool(team.get("joinEnabled") and team.get("canAcceptMembers"))


def one_line(fragment):
    return re.sub(r"\s+", " ", md(fragment)).strip()


def load(name):
    return json.loads((DATA / f"{name}.json").read_text())


def write(rel, body):
    path = DOCS / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(GENERATED + body.strip() + "\n")
    print(f"  wrote docs/{rel}")


def clear(folder):
    """Empty a generated folder, so pages removed from the site don't linger."""
    target = DOCS / folder
    if target.exists():
        shutil.rmtree(target)


def url(rel):
    return SITE + rel if rel else ""


def blocks(content):
    """Render a Wagtail stream field (list of blocks) as Markdown."""
    out = []
    for block in content or []:
        kind, value = block.get("__typename"), block.get("value") or {}
        if kind == "HtmlBlock":
            out.append(md(value.get("html")))
        elif kind == "AccordionBlock":
            if value.get("title"):
                out.append(f"### {value['title']}")
            for panel in value.get("panels") or []:
                out.append(f"**{(panel.get('title') or '').strip()}**\n\n{md(panel.get('richText'))}")
        elif kind == "TileGroupBlock":
            if value.get("title"):
                out.append(f"### {value['title']}")
            out.append(md(value.get("richText")))
            for tile in value.get("tiles") or []:
                out.append(json.dumps(tile, ensure_ascii=False) if not isinstance(tile, dict)
                           else "- " + " | ".join(str(v) for v in tile.values() if isinstance(v, str) and v))
        elif kind == "EventTaskGroupBlock":
            for task in value.get("tasks") or []:
                out.append(f"- **{(task.get('title') or '').title()}** ({melbourne_date(task.get('endDate'))}): {task.get('description') or ''}")
    return "\n\n".join(x for x in out if x)


def build_event():
    le, ev, home = load("local_event"), load("event"), load("event_home")
    meta = load("scrape_meta")
    lon, lat = (le.get("venueGeoLocation") or {}).get("coordinates") or [None, None]
    schedule = "\n".join(
        f"| {cell((s.get('startDate') or '?').replace('T', ' ')[:16])} | {cell(s.get('title'))} | "
        f"{cell(s.get('description'))} |"
        for s in le.get("schedule") or [])
    starts = [s["startDate"].replace("T", " ")[:16] for s in le.get("schedule") or [] if s.get("startDate")]
    first, last = (min(starts), max(starts)) if starts else ("?", "?")
    leads = ", ".join(f"{m['userDetails']['fullName']} (@{m['userDetails']['username']})"
                      for m in le.get("memberships") or [] if m.get("userDetails"))
    body = f"""# Melbourne local event: NASA Space Apps 2026

Scraped {meta['scrapedAt']} from {meta['source']}

## Key facts

| | |
|---|---|
| Dates | {first} to {last} (Melbourne time) |
| Format | {le.get('eventType')}{' (hybrid)' if le.get('isHybrid') else ''} |
| Venue | {' '.join(x for x in (le.get('venueName'), le.get('venueAddress')) if x) or 'To be confirmed'} (map pin {lat}, {lon}) |
| Timezone | {le.get('timezone')} |
| Registered | {le.get('realTimeRegistrations')} of {le.get('registrationLimit')} places (waitlist {le.get('realTimeWaitlist')}) |
| Registration open | {'yes' if le.get('isRegistrationOpen') else 'no'} |
| Cost | Free |
| Local lead | {leads or 'n/a'} |
| Contact | {le.get('contactEmail') or 'n/a'} |
| Team size limit | {ev.get('teamMemberLimit')} people |
| Melbourne page | {url(le['meta']['relativeUrl'])} |

## Melbourne schedule

| When (Melbourne time) | What | Details |
|---|---|---|
{schedule}

## About the Melbourne event

{md(le.get('richtextContent'))}

## Global steps and deadlines

{blocks(home.get('content'))}

## Global event numbers

| | |
|---|---|
| Local events worldwide | {ev.get('cachedLocalEvents')} |
| Registrations worldwide | {ev.get('cachedEventRegistrations')} |
| Challenges | {ev.get('cachedChallenges')} |

## What a project submission contains

| Field | Type |
|---|---|
""" + "\n".join(f"| {cell(f.get('title'))} | {cell(f.get('fieldType'))} |" for f in ev.get("projectFields") or [])
    write("event.md", body)


def build_teams():
    data = load("teams")
    rows, details = [], []
    for t in data["teams"]:
        ch = (t.get("challengeDetails") or {}).get("title") or "none yet"
        skills = ", ".join(t.get("desiredSkills") or []) or "not listed"
        link = url(t["meta"]["relativeUrl"])
        rows.append(f"| [{cell(t.get('title')).replace(']', '\\]')}]({link}) | {cell(ch)} | {cell(skills)} | "
                    f"{'yes' if can_join(t) else 'no'} |")
        details.append(f"### {t.get('title')}\n\n- Challenge: {ch}\n- Looking for: {skills}\n"
                       f"- Open to join: {'yes' if can_join(t) else 'no'}\n"
                       f"- Project submitted: {'yes' if t.get('projectSubmitted') else 'no'}\n"
                       f"- Page: {link}\n\n{md(t.get('excerpt'))}")
    body = f"""# Melbourne teams

{len(data['teams'])} teams as of {data['scrapedAt']}. Member lists are not saved (the team list query returns none).
Refresh with `python3 scraper/scrape.py --teams && python3 scraper/build_docs.py`.

| Team | Challenge | Looking for | Open to join |
|---|---|---|---|
{chr(10).join(rows)}

## Details

{(chr(10) * 2).join(details)}"""
    write("teams.md", body)


def build_challenges():
    # Unknown counts sort last, so they never look like the least crowded challenge.
    challenges = sorted(load("challenges"), key=lambda c: (c.get("globalTeamCount") is None, c.get("globalTeamCount") or 0))
    # Count Melbourne teams from teams.json, which `scrape.py --teams` keeps fresh.
    local = {}
    for t in load("teams")["teams"]:
        local[t.get("challenge")] = local.get(t.get("challenge"), 0) + 1
    clear("challenges")
    rows = []
    for c in challenges:
        name = c["meta"]["slug"]
        levels = ", ".join(x["name"] for x in c.get("categories") or [])
        skills = ", ".join(c.get("skills") or [])
        worldwide = c.get("globalTeamCount") if c.get("globalTeamCount") is not None else "?"
        melbourne = local.get(c["id"], 0)
        rows.append(f"| [{cell(c['title'])}]({name}.md) | {cell(levels)} | {cell(skills)} | {worldwide} | {melbourne} |")
        body = f"""# {c['title']}

| | |
|---|---|
| Level | {cell(levels)} |
| Skills | {cell(skills)} |
| Teams worldwide | {worldwide} |
| Teams in Melbourne | {melbourne} |
| Official page | {url(c['meta']['relativeUrl'])} |

## Challenge

{md(c.get('detailsContent')) or md(c.get('excerpt'))}
"""
        if md(c.get("resourcesTabContent")):
            body += f"\n## Resources\n\n{md(c['resourcesTabContent'])}\n"
        write(f"challenges/{name}.md", body)
    index = f"""# 2026 challenges

{len(challenges)} challenges, sorted by fewest teams worldwide (less competition first).
Only short summaries are out now. Full challenge statements, with data sources, are due 28 Oct 2026.
Rerun the scraper then.

| Challenge | Level | Skills | Teams worldwide | Teams in Melbourne |
|---|---|---|---|---|
{chr(10).join(rows)}"""
    write("challenges/README.md", index)


def build_guides():
    clear("guides")
    for guide in load("guides"):
        parts = [f"# {guide['title']}", f"Source: {url(guide['meta']['relativeUrl'])}", md(guide.get("summary"))]
        for res in guide.get("resources") or []:
            parts.append(f"## {res['title']}")
            parts.append(blocks(res.get("content")))
        write(f"guides/{guide['meta']['slug']}.md", "\n\n".join(p for p in parts if p))
    for info in load("info_pages"):
        parts = [f"# {info['title']}", f"Source: {url(info['meta']['relativeUrl'])}",
                 md(info.get("heroContent")), blocks(info.get("content"))]
        write(f"guides/{info['meta']['slug']}.md", "\n\n".join(p for p in parts if p))


def build_winners():
    w = load("past_winners")
    parts = [f"# {w['title']} (2025)",
             f"Source: {w['url']}",
             "What won last year. Use it to see the bar and what judges reward."]
    for award in w["awards"]:
        parts.append(f"## {award['name']}")
        if award.get("description"):
            parts.append(one_line(award["description"]))
        for t in award["teams"]:
            p = t.get("projectDetails") or {}
            ch = (t.get("challengeDetails") or {}).get("title") or "?"
            loc = (t.get("locationDetails") or {}).get("title") or "?"
            links = " · ".join(f"[{label}]({html.unescape(link)})" for label, link in
                               (("demo", p.get("demoLink")), ("project", p.get("projectLink")),
                                ("team page", url(t["meta"]["relativeUrl"]))) if link)
            summary = (p.get("summary") or "").strip().replace("\n\n", "\n\n> ")
            parts.append(f"### {t['title']}: {p.get('name') or ''}\n\n"
                         f"- Challenge: {ch}\n- Local event: {loc}\n- Links: {links}\n\n> {summary}")
    write("past-winners-2025.md", "\n\n".join(parts))


def main():
    print("Building docs")
    build_event()
    build_teams()
    build_challenges()
    build_guides()
    build_winners()


if __name__ == "__main__":
    main()
